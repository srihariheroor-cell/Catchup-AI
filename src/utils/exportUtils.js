// Export & Download Utilities for CatchUp AI

/**
 * Generates formatted Markdown representation of analysis
 */
export function generateMarkdownReport(analysis, title = "CatchUp AI Summary") {
  const dateStr = new Date().toLocaleString();
  let md = `# ⚡ ${title}\n`;
  md += `*Generated by CatchUp AI on ${dateStr}*\n`;
  md += `*Engine: ${analysis.engineName || "Local Heuristic NLP"}*\n\n`;

  md += `## 📊 Quick Overview\n`;
  md += `- **Urgency Level**: ${analysis.urgencyLevel?.toUpperCase() || "NORMAL"}\n`;
  md += `- **Messages Processed**: ${analysis.stats?.totalMessages || 0}\n`;
  md += `- **Noise Filtered**: ~${analysis.stats?.noiseFilteredPercent || 0}%\n`;
  md += `- **Estimated Time Saved**: ${analysis.stats?.timeSavedMinutes || 0} minutes\n`;
  md += `- **Group Sentiment**: ${analysis.stats?.sentiment || "N/A"}\n\n`;

  md += `## 📝 Executive Summary\n`;
  md += `${analysis.summary}\n\n`;

  if (analysis.keyTakeaways && analysis.keyTakeaways.length > 0) {
    md += `### Key Takeaways\n`;
    analysis.keyTakeaways.forEach(k => {
      md += `- ${k}\n`;
    });
    md += `\n`;
  }

  if (analysis.urgentMessages && analysis.urgentMessages.length > 0) {
    md += `## 🚨 Urgent & Important Messages\n`;
    analysis.urgentMessages.forEach(u => {
      md += `> **[${u.time}] ${u.sender}**: "${u.content}"\n`;
      md += `> *Flagged Reason: ${u.reason}*\n\n`;
    });
  }

  if (analysis.tasks && analysis.tasks.length > 0) {
    md += `## ✅ Action Items & Tasks\n`;
    analysis.tasks.forEach(t => {
      const box = t.completed ? "[x]" : "[ ]";
      md += `- ${box} **${t.task}** | Assignee: \`${t.assignee}\` | Priority: **${t.priority?.toUpperCase()}** | Due: ${t.deadline}\n`;
    });
    md += `\n`;
  }

  if (analysis.deadlines && analysis.deadlines.length > 0) {
    md += `## 📅 Deadlines & Scheduled Meetings\n`;
    analysis.deadlines.forEach(d => {
      md += `- **${d.event}** — \`${d.time}\` (Location: ${d.location})${d.isUrgent ? " ⚠️ URGENT" : ""}\n`;
    });
    md += `\n`;
  }

  if (analysis.decisions && analysis.decisions.length > 0) {
    md += `## ⚖️ Key Decisions Made\n`;
    analysis.decisions.forEach(dec => {
      md += `- 🎯 ${dec}\n`;
    });
    md += `\n`;
  }

  if (analysis.participants && analysis.participants.length > 0) {
    md += `## 👥 Active Participants\n`;
    analysis.participants.forEach(p => {
      md += `- **${p.name}** (${p.role || "Member"}): ${p.messages} messages\n`;
    });
    md += `\n`;
  }

  md += `---\n*Privacy Note: ${analysis.privacyGuarantee || "Processed safely."}*\n`;
  return md;
}

/**
 * Generates plain text version
 */
export function generatePlainTextReport(analysis, title = "CatchUp AI Summary") {
  return generateMarkdownReport(analysis, title)
    .replace(/#{1,6}\s+/g, "")
    .replace(/\*\*/g, "")
    .replace(/\*/g, "")
    .replace(/`/g, "")
    .replace(/>\s*/g, "  | ");
}

/**
 * Downloads a file to the user's computer via browser blob
 */
export function downloadFile(content, filename, mimeType = "text/plain") {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Generates an .ics calendar file for upcoming deadlines
 */
export function generateIcsCalendar(deadlines, title = "CatchUp AI Deadlines") {
  let ics = "BEGIN:VCALENDAR\nVERSION:2.0\nPRODID:-//CatchUp AI//College Hackathon//EN\n";

  const now = new Date();
  const formatIcsDate = (d) => {
    return d.toISOString().replace(/[-:]/g, "").split(".")[0] + "Z";
  };

  (deadlines || []).forEach((d, i) => {
    // Generate event ~1 hour duration for upcoming
    const start = new Date(now.getTime() + (i + 1) * 3600000);
    const end = new Date(start.getTime() + 3600000);

    ics += "BEGIN:VEVENT\n";
    ics += `UID:catchup-${Date.now()}-${i}@catchup.ai\n`;
    ics += `DTSTAMP:${formatIcsDate(now)}\n`;
    ics += `DTSTART:${formatIcsDate(start)}\n`;
    ics += `DTEND:${formatIcsDate(end)}\n`;
    ics += `SUMMARY:${d.event.replace(/\n/g, " ")}\n`;
    ics += `LOCATION:${d.location || "Campus"}\n`;
    ics += `DESCRIPTION:Extracted by CatchUp AI from group conversation. Scheduled at: ${d.time}\n`;
    ics += "END:VEVENT\n";
  });

  ics += "END:VCALENDAR";
  return ics;
}
